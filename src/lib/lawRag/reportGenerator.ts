import type { LlmClient } from '../llm/llmClient.js';
import { logger } from '../logger.js';

/**
 * 法令レポート生成（移植元 law_report_pipeline._generate_complete_report /
 * PROMPT_GENERATE_COMPLETE_REPORT の on-prem 移植）。
 *
 * 参考情報（選別済み条文を番号付きにしたテキスト）をクエリと共に LLM へ渡し、引用付きレポートを 1 回で
 * 生成する。引用番号 [n] の本文中付与・条文番号検証・本体法/政令の区別といった移植元の品質規律は維持しつつ、
 * 実行環境を on-prem ローカル LLM（gemma）へ合わせて prompt を調整する。
 *
 * 上流との差分（gemma / on-prem 適応・明示）:
 *   - web 検索・url_context が無いため、情報源の優先順位から Web 検索結果・URL コンテキスト階層を除去。
 *     参考情報＝【e-laws公式条文】を唯一の一次根拠とし、不足時のみ学習データ（その旨明示）に縮約。
 *   - 「参照リスト・出典は生成しない（後処理で付与）」は維持（出典結合は Step4 _finalize 相当が担う）。
 *   - gemma 対策＝思考過程の前置きを禁止し、最初の見出し前の前置き文は後処理（stripReportPreamble）で除去。
 *     `<think>…</think>` 等の思考タグも保険的に除去する（移植元 extract_text_without_thinking の代替）。
 *   - 生成パラメータ（temperature 0 等）は LlmClient seam が公開しないため当面 prompt 側の規律で代替する
 *     （seam 拡張時に strict config を後続で配線）。
 *   - 【2026-09-19 追加】該当条文が無ければ無いと答える規律と、未施行条文（施行予定）の言い回しを足す。
 *     いずれも上流 prompt に無い項目で、上流が web grounding で担保していた「存在しないものは存在しないと
 *     言える」性質を、参考情報だけで成立させるための指示。
 */

/** gemma 向けレポート生成システムプロンプト（移植元 PROMPT_GENERATE_COMPLETE_REPORT の gemma/on-prem 適応）。 */
export const GENERATE_REPORT_SYSTEM_PROMPT = `参考情報に基づき、完全な法令レポートを1回で生成してください。

## クエリ分類と必須構成要素
まず以下の6パターンからクエリに最も適したものを選び、対応する必須構成要素を全てセクションとして含めてください。

- **定義確認型**（用語・概念の法的定義を求める）: 簡潔定義 / 根拠条文の引用 / 具体例・補足
- **手続き確認型**（法的手続き・申請方法の詳細を求める）: 要件チェックリスト / 手続きフロー / 必要書類・期限・費用 / 注意点
- **比較検討型**（複数の制度・選択肢の比較を求める）: 比較の観点と判断基準 / 推奨パターン・使い分け / 実務上の留意点
- **解釈適用型**（具体的状況への法律適用の解釈を求める）: 基本原則・判断基準 / 適用要件の整理 / 判例・解釈例 / 適用限界・例外ケース / 実務的判断指針
- **政策研究型**（法制度の論点・歴史・展望の分析を求める）: 現状の課題整理 / 改正の方向性・選択肢 / 政策提言・具体案 / 実現可能性・課題
- **包括分析型**（多角的な網羅的解説を求める）: 論点の全体構造 / 法的側面の分析 / 実務的課題の整理 / 関連判例・解釈の検討 / 今後の展望・課題

## 引用ルール（必須・厳守）
参考情報には \`[1]\`, \`[2]\`, \`[3]\` ... のように番号が付与されています。本文を書く際は以下のルールを**必ず**守ってください。

- **本文中で必ず引用番号を記載すること**: 参考情報の内容を使った文・段落には、必ず文末または文中に \`[番号]\` を付けること
  - 例: 「民法第709条は不法行為責任を規定しています [1]。」
  - 例: 「個人情報の定義（[2]）および取得制限（[3]）に留意が必要です。」
- **引用は必要最小限でよい**: 根拠として使用した参考情報のみ引用すること。全ての番号を引用する必要はない
- **複数の番号をまとめて引用してもよい**: 複数の参考情報が同一の主張を支持する場合、\`[1, 3]\` のようにカンマ区切りで記載すること
- **参照リスト・出典リスト・URLリストのセクションは生成しないでください**（後処理で自動追加されます）

## 情報源の優先順位（厳守）
参考情報に含まれる各エントリは以下の順位で扱うこと：
1. **【e-laws公式条文】と明記されたエントリ** — 条文番号・条文内容の唯一の根拠。自己の学習データより必ず優先し、内容・番号を上書きしてはならない
2. **自己の学習データ** — 参考情報に該当条文が存在しない場合のみ使用し、「参考情報に記載がないため学習データに基づく」と明示すること

## 該当条文が無い場合（厳守）
- 参考情報にクエリへ答える条文が含まれていない場合は、**無いことを明示**すること。近い内容の別の条文を根拠として代用してはならない。
- 「参考情報には該当する条文が含まれていません」と述べたうえで、分かる範囲の一般的な説明にとどめ、条文番号を創作しない。

## 未施行（施行予定）の条文を扱う場合（厳守）
- 参考情報の冒頭に【施行予定の通知】がある場合は、**回答の最初に「その法令はまだ施行されていない」ことを述べる**こと。
- 条文の内容は「施行後にこうなる」という形で案内し、現に効力があるかのように書かないこと。
- 施行日は通知に示された文言どおりに述べること。「政令で定める日」のように確定していない場合は日付を断定しない。

## 重要な指示
- レポートは日本語で書いてください
- 選択したパターンの必須構成要素の各項目を、必ずセクション（## 見出し）として含めてください
- セクション間で内容の重複を避け、一貫性のあるレポートを作成してください
- **全体の文字数は3,000字程度以内に収めてください**（リード文から結論まで。出典セクションは除く）

## 記述ルール
- 条文は正確に引用し、条文番号を明記
- 専門用語は適切に解説
- 実務的な観点を重視
- 読みやすい構成と文体
- 不確実な内容は推測せず、確実な情報のみを記載。ユーザーのクエリで通称名称が使われている場合は、対応する正式な法令名を明記する
- テーブルレイアウトは利用しない
- **条文番号の検証（最重要）**: クエリで条文番号が指定されている場合、**回答の冒頭で必ず**その条文番号を検証すること。検証には参考情報を優先し、参考情報に当該条文が含まれない場合は自己の学習データで照合すること。以下の3パターンで対応すること。
  - **タイトル不一致**: クエリが「第X条の○○」と述べているとき、参考情報または学習データにおける第X条のタイトルが○○と一致しない場合は「クエリの条文番号は誤りです。第X条は○○（実際のタイトル）の規定です。ご質問の内容は第Y条（○○）に該当します」と**回答の最初に明記して訂正**し、正しい条文に基づいて回答すること
  - **条文が参考情報に存在しない**: クエリで具体的な条文番号が指定されているにも関わらず参考情報にその番号が見当たらない場合は、必ず「ご指定の第X条は参考情報では確認できませんでした。存在しない条文番号の可能性があります。最も関連する第Z条（○○）の内容に基づいてレポートします」と**回答の冒頭で明示**し、参考情報中の最も関連する条文で回答すること。学習データに基づいて存在しない条文の内容を創作してはならない
  - **法令名が参考情報と一致しない**: クエリで指定された法令名が参考情報に見当たらない・または類似名称の別法令が使用された場合は、「ご指定の「○○法」は参考情報では確認できませんでした。実在しない法令名の可能性があります。最も近い「△△法」の内容に基づいてレポートします」と**回答の冒頭で読み替えを明示**すること
- **条文番号は参考情報から引用**: 条文番号は必ず参考情報（取得した条文データ）に記載されているものを使用すること。参考情報に記載のない条文番号を断言してはならない。廃止・改正前の法令や条文が指定された場合は廃止・改正の事実を明示し、対応する現行条文を参考情報の範囲で案内すること
- **本体法と政令・省令の区別**: 条文の所在を案内する際は、本体法（○○法第X条）と政令（○○法施行令第Y条）・省令を明確に区別して記載すること

## 思考過程の禁止
- 思考・検討の過程や前置き文を出力しないこと。最初の出力は必ずレポートのタイトル見出し（# ）から始めること。

## 出力形式
以下の形式で完全なレポートを出力してください：

# レポートタイトル

**リード文（140-280文字）**

## セクション1タイトル
詳細な内容...

## セクション2タイトル
詳細な内容...

## 結論
主要な論点の整理、実務上の重要なポイント、今後の展望や課題、注意すべき事項を含む実践的な結論`;

// ---- 純関数（LLM 不要・ユニットテスト対象） ----------------------------------------------

/** `<think>…</think>` 等の思考タグを除去する（移植元 extract_text_without_thinking の代替・保険）。 */
export function stripThinkBlocks(text: string): string {
  return (text ?? '').replace(/<think(?:ing)?>[\s\S]*?<\/think(?:ing)?>/gi, '');
}

/**
 * 最初の Markdown 見出し（`#`）より前の前置き（思考的な導入文）を除去する（移植元と同処理）。
 * 見出しが無ければ全文をそのまま返す（trim のみ）。
 */
export function stripReportPreamble(text: string): string {
  const cleaned = stripThinkBlocks(text);
  const m = cleaned.match(/^#/m);
  if (m && m.index !== undefined) {
    return cleaned.slice(m.index);
  }
  return cleaned.trim();
}

/**
 * レポート生成のシステムプロンプトを解決する（設定上書き対応・on-prem 追加）。
 *
 * `LAW_RAG_REPORT_PROMPT_FILE` にファイルパスが指定されていればその内容を、なければ組込み既定
 * （GENERATE_REPORT_SYSTEM_PROMPT）を返す。ローカル LLM（gemma 等）に合わせたプロンプト調整を**再ビルド
 * なし**（ファイル差し替え＋api 再起動）で試せるようにする。指定パスが読めないときは既定へ安全フォールバック
 * （誤設定で起動や生成を壊さない）。構築時に 1 度だけ解決する（反映は api 再起動で）。
 */
export function resolveReportSystemPrompt(env: NodeJS.ProcessEnv = process.env): string {
  const file = env.LAW_RAG_REPORT_PROMPT_FILE?.trim();
  if (file) {
    try {
      const content = readFileSync(file, 'utf8').trim();
      if (content.length > 0) {
        return content;
      }
      logger.warn({ file }, 'LAW_RAG_REPORT_PROMPT_FILE は空のため既定プロンプトを使用します');
    } catch (err) {
      logger.warn(
        { file, error: (err as Error)?.message },
        'LAW_RAG_REPORT_PROMPT_FILE を読めないため既定プロンプトを使用します',
      );
    }
  }
  return GENERATE_REPORT_SYSTEM_PROMPT;
}

// ---- 生成器（LlmClient 注入） -----------------------------------------------------------

export class ReportGenerator {
  private readonly systemPrompt: string;

  /** systemPrompt 未指定時は設定（LAW_RAG_REPORT_PROMPT_FILE）→組込み既定の順で解決する。 */
  constructor(
    private readonly llm: LlmClient,
    systemPrompt: string = resolveReportSystemPrompt(),
  ) {
    this.systemPrompt = systemPrompt;
  }

  /** 参考情報テキストとクエリから引用付きレポートを 1 回で生成する（移植元 _generate_complete_report）。 */
  async generate(
    query: string,
    referencesText: string,
    model: string,
    requestId: string,
  ): Promise<string> {
    const raw = await this.llm.generate({
      model,
      messages: [
        { role: 'system', content: this.systemPrompt },
        { role: 'user', content: `クエリ: ${query}\n\n参考情報:\n${referencesText}` },
      ],
      requestId,
    });
    return stripReportPreamble(raw);
  }
}
